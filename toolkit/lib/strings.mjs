// Portuguese needs the product's article: "o Avvi", "a Clientela", or none.
export function articles(article = "o") {
  const a = String(article || "").toLowerCase();
  return a === "a" ? { o: "a ", O: "A ", do: "da ", no: "na " } : a === "o" ? { o: "o ", O: "O ", do: "do ", no: "no " } : { o: "", O: "", do: "de ", no: "em " };
}

export const fill = (text, values = {}) => String(text ?? "").replace(/\{(\w+)\}/g, (_, key) => values[key] ?? `{${key}}`);
